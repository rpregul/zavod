export const WORDS = [...new Set(RAW.split(/\s+/).filter((w) => w.length >= 4))];

// 30 слов: без пар с одинаковым началом (чтобы не путать окончания), длина 5-10 букв предпочтительна
export function pickWords(n = 30, rnd = Math.random) {
  const pool = shuffle(WORDS, rnd);
  const out = [];
  const stems = new Set();
  for (const w of pool) {
    const stem = w.slice(0, 4);
    if (stems.has(stem)) continue;
    if (w.length > 11) continue;
    stems.add(stem);
    out.push(w);
    if (out.length === n) break;
  }
  return out;
}
